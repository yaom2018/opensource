# -*- coding: utf-8 -*-
"""把 _build/vocab_1001_2000.json 生成 Day08.md 风格的日课文件（盲测 20 题一组，组后立刻给折叠答案）。

用法：python _build/gen_day.py 12 [输出路径]
"""
import json
import os
import sys

SRC = "_build/vocab_1001_2000.json"
PDF_NAME = "N1語彙1001-2000簡体字.pdf"
GROUP = 20  # 盲测每组题数


def load(day_first, count=100):
    data = json.load(open(SRC, encoding="utf-8"))
    return [e for e in data if day_first <= e["id"] < day_first + count]


def pages_of(entries):
    out = []
    for e in entries:
        if not out or out[-1][0] != e["page"]:
            out.append((e["page"], []))
        out[-1][1].append(e)
    return out


def answer_line(e):
    right = e["optA"] if e["ans"] == "A" else e["optB"]
    wrong = e["optB"] if e["ans"] == "A" else e["optA"]
    return f"{e['id']}　{e['word']}｜{e['reading']}｜{e['cn']}　→ **{e['ans']}**（正确 {right}／干扰 {wrong}）"


def gen(entries, day, review_day):
    first, last = entries[0]["id"], entries[-1]["id"]
    pfirst, plast = entries[0]["page"], entries[-1]["page"]
    n = len(entries)
    ngroups = (n + GROUP - 1) // GROUP
    L = []
    A = L.append
    A(f"# Day {day:02d} ｜ 词 {first}–{last}")
    A("")
    A(f"**教材**：`{PDF_NAME}`（词 {first}–{last}，p.{pfirst}–p.{plast}）")
    A(f"**今天**：学 {n} 词 → 2 选 1 盲测 {n} 题（{GROUP} 题一组，做完一组立刻对答案）")
    A(f"**本日词条的回看日**：+1 → Day {review_day:02d}　｜　+3 → Day {review_day + 2:02d}　｜　+7 → Day {review_day + 6:02d}")
    A(f"**记录**：盲测正确 ____ / {n}　｜　错题 ____ 个　｜　用时 ____ 分")
    A("")
    A("> **顺序**")
    A("> ① 先过**第一节学习页**：出声读、看例句、记搭配（读音单独一行，方便你盖住默写）；每 25 词一组，全过完后看「词群 / 搭配速记 / 语感提醒」三张表")
    A(f"> ② 再回**第二节做 2 选 1**：**{GROUP} 题一组**，一组做完立刻展开该组的折叠答案；选项**故意不标读音**，别靠提示猜")
    A("> ③ 每组对完答案 → 立刻把**第三节「易混对速记」**抄一遍（这一步决定这天记不记得住）")
    A("> ④ 选错的在**第四节**做**错题回炉**（遮住选项写「字 + 读音」）")
    A("> ⑤ **复习日（+1 / +3 / +7）顺序反过来**：先做题、再看学习页，先测出来的错才是真错；第五节写了每天做什么")
    A("> ⑥ 错题抄进 `../错词本.md`，只攻错题")
    A("> ⑦ 选项里的读音 / 释义来自本书；中文栏是教材原文，判断词义以日语释义为准；「搭配速记 / 语感提醒」两张表是我按商务 IT 场景补的（补充）")
    A("")
    A("**今天相对 Day08 模板改了什么（8 处）**")
    A("")
    A("| 改动 | Day08 的做法 | 现在 | 为什么 |")
    A("| --- | --- | --- | --- |")
    A("| 选项提示 | 正确项后面标「读音｜中文」 | **两个选项都不标** | 标了正确项等于把答案写在脸上，盲测会变成「认提示」 |")
    A("| 干扰项 | 教材自带 | 教材自带，答案区同时写「正确／干扰」 | N1 词汇题考的就是「两个都像，选一个」，干扰项本身就是知识点 |")
    A("| 学习分组 | 100 词一口气过 | 每 25 词一组（＝教材 1 页），组后 3 分钟快过 | 切小块回头率高；100 词连着背，后面全糊 |")
    A(f"| 盲测答案 | 100 题做完再翻统一答案 | **{GROUP} 题一组，组后立刻折叠给答案** | 一次对 100 个答案太费劲，也对不出「哪一组最弱」 |")
    A("| 易混对照 | 无 | 学习页末「词群」＋第三节「易混对速记」 | 同音／同形词集中对撞，比分散记牢得多 |")
    A("| **搭配速记** | 只有教材例句 | 学习页末新增「商务／IT 现场搭配」＋现场例句 | 教材例句是通用语境，工作里真正要用的是固定搭配 |")
    A("| **语感提醒** | 无 | 「意思懂但用错」清单＋读音易错点 | N1 和现场最容易翻车的不是词义，是正式度和搭配对象 |")
    A("| 复习 | 只写回看日 | 写明 +1 / +3 / +7 是哪天、做什么（第五节） | 到那天不用再想计划 |")
    A("")
    A("---")
    A("")
    A("## 一、学习页（先学一遍，60–90 分钟）")
    A("")
    A("做法：每条读 3 遍——① 看字写读音（盖住「读音」行）② 读日语释义 ③ 出声读例句，把搭配一起读出来")
    A("")
    A("> 每 25 词一组（对应教材 1 页）。一组读完停 3 分钟，回头只看「词 + 读音」两列快速过一遍，再进下一组。")
    A("")
    for page, es in pages_of(entries):
        A(f"### {PDF_NAME}　p.{page}（{es[0]['id']}–{es[-1]['id']}）")
        A("")
        for e in es:
            A(f"**{e['id']} {e['word']}**　{e['cn']}")
            A(f"　读音：{e['reading']}")
            A(f"　日：{e['jp']}")
            A(f"　例：{e['example']}")
            A(f"　译：{e['trans']}")
            A("")
    A("### 本日词群（同前缀 / 同后缀，先放一起记）")
    A("")
    A("<!--PLACEHOLDER:GROUPS-->")
    A("")
    A("### 本日搭配速记（挑出商务 / IT 现场真能用上的词）")
    A("")
    A("<!--PLACEHOLDER:COLLOC-->")
    A("")
    A("### 本日语感提醒（最容易「意思懂、但用错」的地方）")
    A("")
    A("<!--PLACEHOLDER:NUANCE-->")
    A("")
    A("---")
    A("")
    A(f"## 二、2 选 1 盲测（{GROUP} 题一组，做完一组立刻对答案）")
    A("")
    A(f"做法：读句子 → 选 A 或 B → 这一组 {GROUP} 题做完，**展开下面该组的折叠答案**立刻批。选完能说出「另一个为什么不行」最好。")
    A("")
    A("> 选项顺序固定：**A 在左、B 在右**（和教材排版一致），抄答案时直接写 A / B 就行。")
    A(">")
    A(f"> 分 {ngroups} 组、每组 {GROUP} 题：错题当场圈出来，直接填到第四节「错题回炉」；**别攒到最后一起对**。")
    A("")
    A(f"**答题卡（一组 {GROUP} 题写完先写这里，再展开该组答案批改；错题直接抄到第四节）**")
    A("")
    A("```text")
    for row in range(0, n, 10):
        cells = [f"{k + 1:02d} __" for k in range(row, min(row + 10, n))]
        A("  ".join(cells))
    A("```")
    A("")
    for g in range(ngroups):
        es = entries[g * GROUP : (g + 1) * GROUP]
        A(f"### 第 {g + 1} 组（{es[0]['id']}–{es[-1]['id']}）")
        A("")
        for e in es:
            A(f"**{e['id']}**　{e['quiz']}")
            A("")
            A(f"　　A {e['optA']}　／　B {e['optB']}　→　我选：____")
            A("")
        A(f"<details><summary>第 {g + 1} 组答案（{es[0]['id']}–{es[-1]['id']}）</summary>")
        A("")
        for e in es:
            A(answer_line(e))
            A("")
        A("</details>")
        A("")
    A("---")
    A("")
    A("## 三、易混对速记（对完答案立刻抄一遍，20 分钟）")
    A("")
    A("<!--PLACEHOLDER:CONFUSE-->")
    A("")
    A("---")
    A("")
    A("## 四、错题回炉（只做选错的，20 分钟）")
    A("")
    A("**做法**：翻回第二节，**遮住 A / B**，只看句子把这几个词写出来（字 + 读音）；写不出来的抄进 `../错词本.md`，按 1 / 3 / 7 天重测。")
    A("")
    A("| 我选错的题号 | 单词 | 读音（自己写） | 我选错成了 | 重测 ✔/✘ |")
    A("| --- | --- | --- | --- | --- |")
    for _ in range(10):
        A("| | | | | |")
    A("")
    A("### 今日自测（10 分钟）")
    A(f"- [ ] 盖住学习页的「读音」行，{n} 词写假名（错几个：____）")
    A(f"- [ ] 盲测正确数：____ / {n}")
    A("- [ ] 错题回炉：____ / ____ 全对")
    A(f"- [ ] {n} 词出声朗读一遍")
    A("")
    A("### 错题台账（抄进错词本）")
    A("")
    A("| # | 单词 | 读音 | 易混词（我选错的） | 错因（①读音 ②近义混同 ③词性活用 ④搭配） | 回看日 |")
    A("| --- | --- | --- | --- | --- | --- |")
    for _ in range(5):
        A("| | | | | | +1 / +3 / +7 |")
    A("")
    A("### 今日感受")
    A("")
    A("- 记不住的词：")
    A("- 明天要注意：")
    A("")
    A("---")
    A("")
    A("## 五、+1 / +3 / +7 复习排程（照做，不用再想）")
    A("")
    A("| 哪天 | 做什么 | 时间 |")
    A("| --- | --- | --- |")
    A(f"| Day {day:02d}（今天） | 学习页 4 组 → 盲测 {n} 题（{GROUP} 题一组） → 易混对速记 → 错题回炉 | 100–130 分钟 |")
    A(f"| Day {review_day:02d}（+1） | **先盲测**（{n} 题，只写答题卡）→ 对答案 → 只回看错的词条 → 易混对速记再抄 10 组 | 40 分钟 |")
    A(f"| Day {review_day + 2:02d}（+3） | 直接看第三节「易混对速记」+ 错词本本日条目；盖住读音默写 30 个错过的词 | 25 分钟 |")
    A(f"| Day {review_day + 6:02d}（+7） | 盖住学习页「读音」行，{n} 词写假名（错 5 个以上 → 整份重做一遍盲测）；再把「搭配速记」右两列遮住，只看词说搭配 | 30 分钟 |")
    A("")
    A("> 记不住的词统一抄进 `../错词本.md`，格式用第四节「错题台账」那张表：错因只写 ①读音 ②近义混同 ③词性活用 ④搭配 四类之一，方便看出自己到底是「不会读」还是「不会用」。")
    A("")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    day = int(sys.argv[1])
    first = 1001 + (day - 11) * 100
    entries = load(first)
    md = gen(entries, day, day + 1)
    out = sys.argv[2] if len(sys.argv) > 2 else f"10天背诵/Day{day:02d}.md"
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(md)
    print("wrote", out, len(md.splitlines()), "lines")
